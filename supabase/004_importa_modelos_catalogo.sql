insert into public.skus (empresa_id, produto_id, cor_id, numero, sku)
select p.empresa_id, p.id, c.id, n, p.ref || '-' || c.sigla || '-' || n
from public.produtos p
join public.cores c on c.empresa_id = p.empresa_id and c.sigla in ('NUD','OFW','PRE','CAR')
cross join generate_series(34,39) n
where p.ref in ('801','802')
on conflict do nothing;